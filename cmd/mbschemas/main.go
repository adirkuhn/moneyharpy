// Command mbschemas copies the structure of the Moneybird API schemas into the
// MoneyHarpy contract.
//
// Moneybird publishes its API as an OpenAPI 3.1 document. MoneyHarpy's
// tooling reads OpenAPI 3.0, and the contract must not carry Moneybird's
// prose, so mbschemas keeps only field names, types, enums and nullability,
// converts them to 3.0 and writes them between markers in api/openapi.yaml.
//
// Usage:
//
//	go run ./cmd/mbschemas [-spec URL-or-file] [-contract api/openapi.yaml] [-check]
//
// With -check it reports whether the contract is up to date instead of
// writing it.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"maps"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

// SpecURL is where Moneybird publishes its API description.
const SpecURL = "https://raw.githubusercontent.com/moneybird/openapi/refs/heads/main/openapi.yml"

const (
	beginMarker = "    # BEGIN Moneybird schemas: generated by cmd/mbschemas, do not edit."
	endMarker   = "    # END Moneybird schemas"
)

// renamed maps Moneybird schemas to the MoneyHarpy schema with the same
// meaning. They are not copied; references point at ours.
var renamed = map[string]string{"identifier": "Identifier", "administration_id": "Identifier"}

// dropped are keywords that carry Moneybird's prose, exist only in 3.1, or
// mean nothing for responses. Defaults go too: Moneybird's spec has some
// that do not match their own type, which 3.0 validators reject.
var dropped = []string{"description", "example", "examples", "unevaluatedProperties", "$comment", "title", "default"}

// branchRules lists, per type, the keywords that belong to that type and move
// to its branch when a list of types becomes anyOf.
var branchRules = map[string][]string{
	"string": {"pattern", "format", "minLength", "maxLength"},
	"array":  {"items", "minItems", "maxItems"},
	"object": {"properties", "additionalProperties", "required"},
}

func main() {
	specFlag := flag.String("spec", SpecURL, "Moneybird OpenAPI document, as a URL or a file")
	contract := flag.String("contract", "api/openapi.yaml", "contract to update")
	check := flag.Bool("check", false, "fail when the contract is out of date instead of writing it")
	flag.Parse()
	if err := run(*specFlag, *contract, *check); err != nil {
		fmt.Fprintln(os.Stderr, "mbschemas:", err)
		os.Exit(1)
	}
}

func run(specRef, contract string, check bool) error {
	raw, err := load(specRef)
	if err != nil {
		return err
	}
	block, err := render(raw)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(contract)
	if err != nil {
		return err
	}
	updated, err := replaceBlock(string(current), block)
	if err != nil {
		return err
	}
	if check {
		if updated != string(current) {
			return errors.New("the Moneybird schemas changed; run go run ./cmd/mbschemas and review the diff")
		}
		return nil
	}
	return os.WriteFile(contract, []byte(updated), 0o644)
}

func load(ref string) ([]byte, error) {
	if !strings.HasPrefix(ref, "https://") {
		return os.ReadFile(ref)
	}
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(ref)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: %s", ref, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// render converts the spec's schemas into the YAML block for the contract.
func render(raw []byte) (string, error) {
	var spec map[string]any
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		return "", fmt.Errorf("parse spec: %w", err)
	}
	converted, err := schemas(spec)
	if err != nil {
		return "", err
	}
	var out strings.Builder
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(converted); err != nil {
		return "", err
	}
	var b strings.Builder
	for line := range strings.Lines(out.String()) {
		b.WriteString("    " + line)
	}
	return b.String(), nil
}

// schemas returns the converted component schemas, keyed by Moneybird's name.
func schemas(spec map[string]any) (map[string]any, error) {
	components, _ := spec["components"].(map[string]any)
	all, ok := components["schemas"].(map[string]any)
	if !ok {
		return nil, errors.New("spec has no component schemas")
	}
	out := map[string]any{}
	for _, name := range slices.Sorted(maps.Keys(all)) {
		if _, skip := renamed[name]; skip {
			continue
		}
		s, ok := convert(all[name]).(map[string]any)
		if !ok {
			return nil, fmt.Errorf("schema %s is not an object", name)
		}
		s["description"] = fmt.Sprintf("Moneybird-compatible %s.", name)
		out[name] = s
	}
	return out, nil
}

// convert rewrites one OpenAPI 3.1 schema, and everything inside it, as 3.0.
func convert(v any) any {
	switch v := v.(type) {
	case []any:
		out := make([]any, len(v))
		for i, x := range v {
			out[i] = convert(x)
		}
		return out
	case map[string]any:
		return convertSchema(v)
	default:
		return v
	}
}

func convertSchema(in map[string]any) map[string]any {
	if ref, ok := in["$ref"].(string); ok {
		name := strings.TrimPrefix(ref, "#/components/schemas/")
		if ours, ok := renamed[name]; ok {
			ref = "#/components/schemas/" + ours
		}
		return map[string]any{"$ref": ref}
	}
	s := map[string]any{}
	for k, v := range in {
		if slices.Contains(dropped, k) {
			continue
		}
		switch k {
		case "properties", "patternProperties":
			props := map[string]any{}
			for name, p := range v.(map[string]any) {
				props[name] = convert(p)
			}
			s[k] = props
		case "const":
			s["enum"] = []any{v}
		default:
			s[k] = convert(v)
		}
	}
	nullable := false
	if types, ok := s["type"].([]any); ok {
		var rest []any
		for _, t := range types {
			if t == "null" {
				nullable = true
			} else {
				rest = append(rest, t)
			}
		}
		delete(s, "type")
		switch len(rest) {
		case 0:
			nullable = true
		case 1:
			s["type"] = rest[0]
		default:
			branches := make([]any, len(rest))
			for i, t := range rest {
				branch := map[string]any{"type": t}
				for _, rule := range branchRules[t.(string)] {
					if r, ok := s[rule]; ok {
						branch[rule] = r
					}
				}
				branches[i] = withItems(branch)
			}
			for _, rules := range branchRules {
				for _, rule := range rules {
					delete(s, rule)
				}
			}
			s["anyOf"] = branches
		}
	}
	if s["type"] == "null" {
		delete(s, "type")
		nullable = true
	}
	for _, key := range []string{"oneOf", "anyOf"} {
		branches, ok := s[key].([]any)
		if !ok {
			continue
		}
		kept := branches[:0:0]
		for _, b := range branches {
			if m, ok := b.(map[string]any); ok && len(m) == 1 && m["nullable"] == true {
				nullable = true
				continue
			}
			kept = append(kept, b)
		}
		s[key] = kept
	}
	if enum, ok := s["enum"].([]any); ok && slices.Contains(enum, any(nil)) {
		s["enum"] = slices.DeleteFunc(slices.Clone(enum), func(e any) bool { return e == nil })
		nullable = true
	}
	if nullable {
		s["nullable"] = true
	}
	return withItems(s)
}

// withItems gives an array schema the items keyword that 3.0 requires.
func withItems(s map[string]any) map[string]any {
	if s["type"] == "array" && s["items"] == nil {
		s["items"] = map[string]any{}
	}
	return s
}

// replaceBlock swaps the text between the markers for block.
func replaceBlock(doc, block string) (string, error) {
	start := strings.Index(doc, beginMarker+"\n")
	end := strings.Index(doc, endMarker)
	if start < 0 || end < start {
		return "", errors.New("contract lacks the Moneybird schema markers")
	}
	return doc[:start+len(beginMarker)+1] + block + doc[end:], nil
}
